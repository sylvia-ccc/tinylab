@dataclass
class Rule:
    rid: str
    level: str                     # "high" | "medium"
    pat: re.Pattern
    reason: str
    ctx: bool = False              # True：需要低落语境才算 high，否则降为 medium
    ctx_risk: bool = False         # True：需要同条或前几轮出现"想结束 / 自杀"等风险语境（RISK_CTX）才算 high，否则降为 medium
    tp: bool = False               # True：命中前同句出现第三方主语（且其后没有"我"）则降为 medium
    neg: Optional[re.Pattern] = None          # 命中所在的整句里出现则整条作废
    neg_before: Optional[re.Pattern] = None   # 命中前 8 个字里出现则作废
    down_before: Optional[re.Pattern] = None  # 命中前 4 个字里出现则降为 medium（夸张用法"累得想死"）


def R(rid, level, pat, reason, **kw) -> Rule:
    neg = kw.pop("neg", None)
    nb = kw.pop("neg_before", None)
    db = kw.pop("down_before", None)
    return Rule(rid, level, re.compile(pat), reason,
                neg=re.compile(neg) if neg else None,
                neg_before=re.compile(nb) if nb else None,
                down_before=re.compile(db) if db else None, **kw)


