# ------------------------------------------------------------------ 扫描
@dataclass
class Hit:
    rule: Rule
    level: str          # 实际级别（可能被 ctx / tp / down 降级）
    text: str           # 命中片段
    downgraded: Optional[str] = None


def _sentence_of(text: str, a: int, b: int) -> tuple[str, str]:
    """返回命中所在整句，以及命中前同句的前缀。"""
    s = max(text.rfind(ch, 0, a) for ch in "。！？!?；;\n")
    s = s + 1 if s >= 0 else 0
    e_candidates = [text.find(ch, b) for ch in "。！？!?；;\n"]
    e_candidates = [x for x in e_candidates if x >= 0]
    e = min(e_candidates) if e_candidates else len(text)
    return text[s:e], text[s:a]


def _clause_prefix(text: str, a: int) -> str:
    """命中前同一分句（逗号分隔）的前缀。"""
    s = max(text.rfind(ch, 0, a) for ch in "。！？!?；;\n,，、")
    return text[s + 1:a] if s >= 0 else text[:a]


def _third_party(prefix: str) -> bool:
    last = None
    for m in THIRD_PARTY.finditer(prefix):
        last = m
    if not last:
        return False
    return "我" not in prefix[last.end():]


def scan(text: str, rules: list[Rule], low_ctx: bool = False, risk_ctx: bool = False) -> list[Hit]:
    """对一条（已规范化的）用户消息跑一组规则。low_ctx 表示同条或前几轮是否有低落语境。"""
    hits: list[Hit] = []
    for rule in rules:
        for m in rule.pat.finditer(text):
            a, b = m.span()
            sent, sent_prefix = _sentence_of(text, a, b)
            if rule.neg and rule.neg.search(sent):
                continue
            if rule.neg_before and rule.neg_before.search(text[max(0, a - 8):a]):
                continue
            level, why = rule.level, None
            if level == "high" and rule.down_before and rule.down_before.search(text[max(0, a - 4):a]):
                level, why = "medium", "夸张用法"
            if level == "high" and rule.tp and _third_party(_clause_prefix(text, a)):
                level, why = "medium", "疑似第三方"
            if level == "high" and rule.ctx and not low_ctx:
                level, why = "medium", "缺少低落语境"
            if level == "high" and rule.ctx_risk and not (risk_ctx or low_ctx):
                level, why = "medium", "缺少风险语境"
            hits.append(Hit(rule, level, m.group(0), why))
            break  # 同一规则在同一条消息里只记一次
    return hits


def _has_low_mood(text: str) -> bool:
    return bool(LOW_MOOD.search(text)) and not RELIEF.search(text)


def _user_texts(messages) -> list[str]:
    out = []
    for m in messages or []:
        if isinstance(m, dict) and m.get("role") == "user":
            out.append(_norm(str(m.get("content", ""))))
    return out


def _fmt(hits: list[Hit]) -> str:
    return "；".join(
        f"{h.rule.rid} {h.rule.reason}「{h.text}」" + (f"（{h.downgraded}，降为 medium）" if h.downgraded else "")
        for h in hits)


def _analyze_crisis(users: list[str], carry: int = 2) -> tuple[Optional[str], str]:
    """返回 (级别, 原因)。级别 "high" | "medium" | None。"""
    last = users[-1]
    prior = users[:-1]
    ctx_window = prior[-4:]
    low_ctx = _has_low_mood(last) or any(_has_low_mood(t) for t in ctx_window)
    risk_ctx = any(RISK_CTX.search(t) for t in [last] + ctx_window)

    last_hits = scan(last, CRISIS_RULES, low_ctx, risk_ctx) + scan(last, MEDIUM_RULES)
    highs = [h for h in last_hits if h.level == "high"]
    meds = [h for h in last_hits if h.level == "medium"]
    if highs:
        return "high", _fmt(highs)

    # 上下文组合：前文攒药 / 备刀，当前消息出现"准备好了 / 放在床头 / 今晚"
    if READINESS.search(last):
        for t in ctx_window:
            m = MEANS_PRIOR.search(t)
            if m and not re.search(DAILY_MED, t):
                return "high", f"C-X1 前文有手段「{m.group(0)}」，当前消息出现准备语「{READINESS.search(last).group(0)}」"

    # 延续：前 carry 轮用户消息里已经有 high，则本轮仍按 high 处理（除非本轮明确是玩笑 / 缓解）
    if carry > 0 and not re.search(r"开玩笑|逗你|说着玩|骗你的|吐槽|没事了|已经好了", last):
        for k in range(1, carry + 1):
            if len(users) - k < 1:
                break
            lvl, why = _analyze_crisis(users[:len(users) - k], carry=0)
            if lvl == "high":
                return "high", f"C-X2 前{k}轮已有高危信号，延续（{why}）"

    # 多个较弱信号叠加：本条有 medium，且前 3 轮 + 本条里累计 ≥2 个不同的 medium 规则
    if meds:
        rids = {h.rule.rid for h in meds}
        for t in prior[-3:]:
            rids |= {h.rule.rid for h in scan(t, MEDIUM_RULES)}
            rids |= {h.rule.rid for h in scan(t, CRISIS_RULES, True, True) if h.level == "medium"}
        if len(rids) >= 2 and low_ctx:
            return "high", f"C-X3 多个较弱信号叠加（{'、'.join(sorted(rids))}）且有低落语境；本条：{_fmt(meds)}"
    if meds:
        return "medium", _fmt(meds)
    return None, ""


def _analyze_identity(last: str) -> tuple[bool, str]:
    hits = scan(last, IDENTITY_RULES)
    if hits:
        return True, _fmt(hits)
    return False, ""


# ------------------------------------------------------------------ 对外接口
class SafetyGate:
    """应用层危机拦截。hotline_text 由产品方按地区配置（写进固定回复里），不要在代码里写死具体号码。"""

    def __init__(self, hotline_text: str = DEFAULT_HOTLINE_TEXT, seed: Optional[int] = None):
        self.hotline_text = hotline_text
        self._rng = random.Random(seed)

    def pick_reply(self, hotline_text: Optional[str] = None) -> str:
        tpl = self._rng.choice(CRISIS_REPLIES)
        return tpl.replace("{hotline}", hotline_text or self.hotline_text)

    def check(self, messages: list[dict], hotline_text: Optional[str] = None) -> dict:
        users = _user_texts(messages)
        res = {"hit": False, "kind": None, "level": None, "reason": None, "reply": None, "system_hint": None, "assistant_prefill": None}
        if not users or not users[-1]:
            return res
        level, why = _analyze_crisis(users)
        if level == "high":
            res.update(hit=True, kind="crisis", level="high", reason=why, reply=self.pick_reply(hotline_text))
            return res
        is_id, id_why = _analyze_identity(users[-1])
        if is_id:
            res.update(hit=True, kind="identity", reason=id_why, system_hint=IDENTITY_HINT, assistant_prefill=IDENTITY_PREFILL)
            if level == "medium":
                res["reason"] += f"（同时有 medium 危机标记：{why}）"
            return res
        if level == "medium":
            res.update(hit=False, kind="crisis", level="medium", reason=why)
        return res


_DEFAULT_GATE = SafetyGate()


def check(messages: list[dict], hotline_text: Optional[str] = None) -> dict:
    """模块级快捷入口，使用默认网关。messages 为 [{"role": "user"|"assistant"|"system", "content": str}, ...]。"""
    return _DEFAULT_GATE.check(messages, hotline_text)
